#!/usr/bin/env node
// 生成两份产物：
// 1. miniprogram/services/local-content.js  —— 包内兜底（archive / cipai / maps / ci-detail）
// 2. miniprogram/services/works-bundled.js —— 内嵌全部作品，给 admin-publish 一键发布云端用
//
// 为什么 works-bundled.js 单独生成：
//   - works 原始文件被 project.config.json 的 packOptions.ignore 排除出包；
//   - 但 admin-publish 管理页需要遍历全部作品来发到云端；
//   - 所以把 works 也内嵌为一个独立 JS 模块（不进 fallback.js，避免用户直接预览所有作品）；
//   - 该文件留在主包里（~400KB），对 2MB 主包限制完全可接受。
//
// 微信小程序 require 不支持 .json 后缀，故必须内嵌为 JS 对象字面量。
//
// 用法：node tools/gen_local_content.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'miniprogram');
const DATA = path.join(ROOT, 'data');
const OUT_LOCAL = path.join(ROOT, 'services', 'local-content.js');
const OUT_WORKS = path.join(ROOT, 'services', 'works-bundled.js');

function loadJson(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function jsStringify(obj) {
  return JSON.stringify(obj, null, 2).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

// ============== 产物 1：local-content.js（兜底数据） ==============
{
  const out = [];
  out.push('// AUTO-GENERATED by tools/gen_local_content.js — 不要手动编辑');
  out.push('// 包内兜底：云模式查不到云端文档时回退到此，保证体验版/正式版无需逐条发布也能显示。');
  out.push('// 云端若发布同名 _id 文档会优先生效，覆盖本兜底。');
  out.push("// 微信小程序 require 不支持 .json 后缀，故此处为内嵌对象而非 require()。");
  out.push("'use strict';");
  out.push('');

  out.push('module.exports = {');
  out.push("  'archive-index': " + jsStringify(loadJson(path.join(DATA, 'archive-index.json'))) + ',');
  out.push("  'archive__all': " + jsStringify(loadJson(path.join(DATA, 'archive-all.json'))) + ',');
  out.push("  'cipai': " + jsStringify(loadJson(path.join(DATA, 'cipai.json'))) + ',');
  out.push("  'maps': " + jsStringify(loadJson(path.join(DATA, 'maps.json'))) + ',');

  const ciDir = path.join(DATA, 'ci-detail');
  const ciFiles = fs.readdirSync(ciDir).filter((f) => f.endsWith('.json')).sort();
  for (const f of ciFiles) {
    const id = f.replace(/\.json$/, '');
    out.push("  'ci-detail__" + id + "': " + jsStringify(loadJson(path.join(ciDir, f))) + ',');
  }
  out.push('};');
  out.push('');

  fs.writeFileSync(OUT_LOCAL, out.join('\n'));
  const kb = (fs.statSync(OUT_LOCAL).size / 1024).toFixed(1);
  console.log('Wrote ' + path.relative(ROOT, OUT_LOCAL) + ' — ci-detail: ' + ciFiles.length + ', size: ' + kb + ' KB');
}

// ============== 产物 2：works-bundled.js（给 admin-publish 用） ==============
{
  const worksDir = path.join(DATA, 'works');
  const files = fs.readdirSync(worksDir).filter((f) => f.endsWith('.json')).sort();

  const out = [];
  out.push('// AUTO-GENERATED by tools/gen_local_content.js — 不要手动编辑');
  out.push('// 内嵌全部作品，仅供 admin-publish 一键发布云端使用。');
  out.push('// 不会自动在页面里被消费（不进 fallback.js），仅为减少云数据库逐条粘贴操作。');
  out.push("// 注意：微信小程序 require 不支持 .json 后缀，故此处为内嵌对象而非 require()。");
  out.push("'use strict';");
  out.push('');

  out.push('module.exports = {');
  for (const f of files) {
    const id = f.replace(/\.json$/, '');
    out.push("  '" + id + "': " + jsStringify(loadJson(path.join(worksDir, f))) + ',');
  }
  out.push('};');
  out.push('');

  fs.writeFileSync(OUT_WORKS, out.join('\n'));
  const kb = (fs.statSync(OUT_WORKS).size / 1024).toFixed(1);
  console.log('Wrote ' + path.relative(ROOT, OUT_WORKS) + ' — works: ' + files.length + ', size: ' + kb + ' KB');
}
# -*- coding: utf-8 -*-
"""Build mini-program offline data from the canonical JSON files."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = REPO_ROOT / "miniprogram" / "data"
OUTPUT = REPO_ROOT / "miniprogram" / "services" / "bundled-data.js"
SOURCES = {
    "course": DATA_DIR / "course.json",
    "weeks": DATA_DIR / "weeks.json",
    "schedule": DATA_DIR / "schedule.json",
    "ci-index": DATA_DIR / "ci-index.json",
    "semester-26spring": DATA_DIR / "semester-26spring.json",
    "books": DATA_DIR / "books.json",
}


def render() -> str:
    data = {
        name: json.loads(path.read_text(encoding="utf-8"))
        for name, path in SOURCES.items()
    }
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    return (
        "// Generated by tools/build_bundled_data.py. Do not edit by hand.\n"
        f"module.exports = {payload};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when bundled-data.js is not synchronized with source JSON",
    )
    args = parser.parse_args()
    expected = render()

    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            print("[FAIL] bundled-data.js needs regeneration")
            return 1
        print("[OK] bundled-data.js is up to date")
        return 0

    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"[OK] {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
